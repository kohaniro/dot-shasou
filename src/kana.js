const DAKU = ['#.#.', '.#.#'], HANDAKU = ['.#.', '#.#', '.#.'];
const BIG = { 'ぁ': 'あ', 'ぃ': 'い', 'ぅ': 'う', 'ぇ': 'え', 'ぉ': 'お', 'ゎ': 'わ' };

/* 文字列 → 字ごとの配置。gap は字間。戻り値 { w, cells: [{ rows, x, y, w, mark }] }（x は左端からの位置、w は字幅） */
export function kanaLayout(str, gap = 1) {
  const cells = []; let x = 0;
  for (const ch of str.normalize('NFD')) {
    if (ch === '゙' || ch === '゚') {
      const c = cells[cells.length - 1];
      if (c && !c.mark) { c.mark = ch === '゙' ? DAKU : HANDAKU; c.w += 2; x += 2; }
      continue;
    }
    const sm = SMALL[ch], rows = sm || G[BIG[ch] || ch];
    if (!rows) continue;
    const w = sm ? 6 : KW;
    cells.push({ rows, x, y: sm ? 3 : 0, w, mark: null });
    x += w + gap;
  }
  return { w: Math.max(0, x - gap), cells };
}
/* (x, y) を左上にして描く。色は P() を通す */
export function drawKana(g, str, x, y, color, gap = 1, layout = null) {
  const lay = layout || kanaLayout(str, gap);
  g.fillStyle = P(color);
  for (const c of lay.cells) {
    const bw = c.mark ? c.w - 2 : c.w;
    c.rows.forEach((row, j) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(x + c.x + i, y + c.y + j, 1, 1); });
    if (c.mark) c.mark.forEach((row, j) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(x + c.x + bw - 2 + i, y + c.y - 1 + j, 1, 1); });
  }
  return lay.w;
}
